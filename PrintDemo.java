class PrintDemo{
	public static void main(String[] args){
		System.out.println("My name is Thamilpriyan");
		System.out.println("My father name is Sujatharan");
		System.out.println("My age is 24");
		
		System.out.println();
		
		System.out.print("My name is Thamilpriyan");
		System.out.print("My father name is Sujatharan");
		System.out.print("My age is 24");
		
		System.out.print("\n");
		
		System.out.print("My name is Thamilpriyan\n");
		System.out.print("My father name is Sujatharan\n");
		System.out.print("My age is 24\n");
		
	}
}



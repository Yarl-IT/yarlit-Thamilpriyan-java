class DecrementOperator{
	public static void main(String [] args){
		int y = 15;
		y = y -5;
		System.out.println(y);
		
		y -= 5;
		System.out.println(y);
		
		y--;
		System.out.println(y);
		
		--y;
		System.out.println(y);
		System.out.println(y--);
		System.out.println(y);
		System.out.println(--y);
		
		//10, 5, 4, 3, 3, 2, 1
	}
}


class IncrementOperator{
	public static void main(String[] args){
		
		int x = 10;
		System.out.println(x);
		
		x = x + 1;
		System.out.println(x);
		
		x += 1;
		System.out.println(x);
		
		x++;
		System.out.println(x);
		
		++x;
		System.out.println(x);
		
		System.out.println(++x);
		System.out.println(x++);
		System.out.println(x);
		
		
		System.out.println();
		
		int y = 10;
		y++;
		System.out.println(y);
		System.out.println(y++);
		System.out.println(++y);
		
	}
}
